use super::HookTarget;

/// earendil-works/pi 1.4.0 only. omp has a different lifecycle contract.
pub(super) fn extension(target: &HookTarget) -> Option<String> {
    let exe = serde_json::to_string(&target.exe.to_string_lossy()).ok()?;
    Some(TEMPLATE.replace("__LYREL_EXE__", &exe))
}

const TEMPLATE: &str = r#"/* lyrel agent-hook pi bridge — generated by lyrel, do not edit. */
import type { ExtensionAPI, ExtensionContext } from "@earendil-works/pi-coding-agent";
import { spawnSync } from "node:child_process";

const EXE = __LYREL_EXE__;
const SCOPE_ENV = ["HOME", "USERPROFILE", "PI_CODING_AGENT_DIR", "PI_CODING_AGENT_SESSION_DIR", "PI_IMAGE_PROTOCOL"];

export default function (pi: ExtensionAPI) {
  if (!process.env["LYREL"]) return;
  // A nested Pi inherits the bridge owner's process identity. Its own
  // session and settlement must not replace the foreground TUI's binding.
  const owner = process.env.LYREL_PI_BRIDGE_OWNER;
  if (owner && owner !== String(process.pid)) return;
  process.env.LYREL_PI_BRIDGE_OWNER = String(process.pid);
  let sequence = 0;
  let outcome: "completed" | "aborted" | "error" | undefined;
  let errorReason: string | undefined;
  const prompts: Array<{ id: string; kind: string; title?: string }> = [];
  function emit(event: string, ctx: ExtensionContext, extra: Record<string, unknown> = {}) {
    // RPC/print/JSON subprocesses are not this pane's foreground native TUI.
    // The public mode field, not output text or a guessed child session ID,
    // keeps their session/settlement reports from taking its binding.
    if (ctx.mode !== "tui") return;
    const file = ctx.sessionManager.getSessionFile();
    const environment = Object.fromEntries(SCOPE_ENV.filter(key => process.env[key] !== undefined).map(key => [key, process.env[key]]));
    const body = {
      session_id: ctx.sessionManager.getSessionId(), cwd: ctx.sessionManager.getCwd(),
      session_scope: { session_file: file, session_dir: ctx.sessionManager.getSessionDir(), environment },
      ...(!file ? { message: "Pi session persistence is disabled; history, resume and fork are unavailable." } : {}),
      ...extra,
    };
    try {
      const report = spawnSync(EXE, ["agent-hook", "pi", event], { input: JSON.stringify(body), stdio: ["pipe", "ignore", "ignore"] });
      if (report.error || report.status !== 0) ctx.ui.notify(`lyrel Pi bridge could not report state: ${report.error?.message ?? `exit ${report.status}`}`, "warning");
    } catch (error) {
      ctx.ui.notify(`lyrel Pi bridge could not report state: ${String(error)}`, "warning");
    }
  }
  pi.on("session_start", (_event, ctx) => {
    prompts.length = 0;
    outcome = undefined;
    errorReason = undefined;
    emit("session-start", ctx);
  });
  const start = (_event: unknown, ctx: ExtensionContext) => {
    outcome = undefined;
    errorReason = undefined;
    emit("prompt-submit", ctx);
  };
  pi.on("before_agent_start", start);
  pi.on("agent_start", start);
  // agent_end ends an attempt, not a run. Even the first attempt may retry,
  // compact, or continue queued/background work: it never emits Stop.
  pi.on("message_end", (event) => {
    const message = event.message;
    if (message.role === "assistant") {
      errorReason = message.stopReason === "error" ? message.errorMessage : undefined;
    }
  });
  pi.on("agent_before_settle", (event) => { outcome = event.outcome; });
  pi.on("agent_settled", (event, ctx) => {
    const result = event.aborted || outcome === "aborted"
      ? { outcome: "interrupted", reason: "Pi agent run aborted" }
      : outcome === "error"
        ? { outcome: "failed", reason: errorReason ?? "Pi agent run failed" }
        : outcome === "completed" ? { outcome: "succeeded" } : undefined;
    emit("stop", ctx, { ...(result ? { result } : { message: "Pi settled without an authoritative activity outcome." }) });
  });
  pi.on("ui_prompt_start", (event, ctx) => {
    // Pi's public TUI event has no request ID. Assign a lifecycle identity;
    // unlike a title-derived ID it keeps repeated dialogs distinct.
    const prompt = { id: `pi-ui-${++sequence}`, kind: event.kind, title: event.title };
    prompts.push(prompt);
    emit(event.kind === "confirm" ? "permission-request" : "question-asked", ctx,
      { request: { id: prompt.id, kind: event.kind === "confirm" ? "permission" : "question", resolved: false } });
  });
  pi.on("ui_prompt_end", (event, ctx) => {
    const candidates = prompts.filter(prompt => prompt.kind === event.kind && prompt.title === event.title);
    if (candidates.length !== 1) {
      emit("notification", ctx, { message: "Pi UI prompt identity is ambiguous or missing; pending requests were preserved." });
      return;
    }
    const prompt = candidates[0];
    prompts.splice(prompts.indexOf(prompt), 1);
    // End carries no approval/answer value; never invent accepted/rejected.
    emit("tool-complete", ctx, { request: { id: prompt.id, kind: prompt.kind === "confirm" ? "permission" : "question", resolved: true } });
  });
  pi.on("session_shutdown", (event, ctx) => {
    emit("session-end", ctx, { message: `Pi session shutdown: ${event.reason}` });
  });
}
"#;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pi_first_run_waits_for_settlement_and_resolves_only_its_own_dialog() {
        let temp = tempfile::tempdir().unwrap();
        let node = std::process::Command::new("node")
            .args(["-p", "process.execPath"])
            .output()
            .expect("Node 22.19+ is required for the Pi integration contract");
        assert!(node.status.success());
        let node = std::path::PathBuf::from(String::from_utf8(node.stdout).unwrap().trim());
        let host = crate::host::local::LocalHost::new();
        let target =
            HookTarget::local_for_exe(&*host, node.clone()).expect("effective local home resolves");
        std::fs::write(temp.path().join("bridge.ts"), extension(&target).unwrap()).unwrap();
        std::fs::write(temp.path().join("agent-hook"), r#"const fs = require('node:fs'); fs.appendFileSync('reports.jsonl', JSON.stringify({event:process.argv[3],...JSON.parse(fs.readFileSync(0,'utf8'))})+'\n');"#).unwrap();
        let script = r#"
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import bridge from './bridge.ts';
const handlers = new Map();
bridge({on(name, fn) { handlers.set(name, fn); }});
const child = spawnSync(process.execPath, ['--input-type=module','--eval', `import bridge from './bridge.ts'; bridge({on(){throw new Error('nested Pi must not register pane hooks')}});`], {encoding:'utf8'});
assert.equal(child.status,0,child.stderr);
const ctx = {mode:'tui',sessionManager:{getSessionId:()=> 'real-pi-source', getSessionFile:()=> '/store/source.jsonl',getSessionDir:()=> '/store',getCwd:()=> '/project'}, ui:{notify(){}}};
const send = (name,event={}) => handlers.get(name)?.(event,ctx);
const reports = () => readFileSync('reports.jsonl','utf8').trim().split('\n').map(JSON.parse);
send('session_start'); send('before_agent_start'); send('agent_end');
assert.equal(reports().some(e=>e.event==='stop'),false,'the first agent_end must never end a retriable run');
handlers.get('session_start')({}, {...ctx,mode:'rpc'});
handlers.get('agent_settled')({aborted:false}, {...ctx,mode:'print'});
assert.equal(reports().length,2,'non-TUI child sessions must not replace the pane owner');
send('ui_prompt_start',{kind:'confirm',title:'allow write'});
send('ui_prompt_start',{kind:'input',title:'choose target'});
send('ui_prompt_end',{kind:'confirm',title:'allow write'});
const r = reports();
assert.notEqual(r[2].request.id,r[3].request.id);
assert.equal(r[4].request.id,r[2].request.id);
assert.equal(r[4].request.resolved,true);
send('ui_prompt_end',{kind:'input',title:'choose target'});
send('message_end',{message:{role:'assistant',stopReason:'error',errorMessage:'provider failed'}});
send('agent_before_settle',{outcome:'error'});
send('agent_settled',{aborted:false});
assert.deepEqual(reports().at(-1).result,{outcome:'failed',reason:'provider failed'});
send('ui_prompt_start',{kind:'select',title:'idle model command'});
send('ui_prompt_end',{kind:'select',title:'idle model command'});
send('agent_start'); send('agent_before_settle',{outcome:'completed'}); send('agent_settled',{aborted:true});
assert.equal(reports().at(-1).result.outcome,'interrupted');
process.stdout.write(reports().map(e=>JSON.stringify(e)).join('\n'));
"#;
        let output = std::process::Command::new(node)
            .args(["--input-type=module", "--eval", script])
            .current_dir(temp.path())
            .env("LYREL", "1")
            .env("HOME", temp.path())
            .env("USERPROFILE", temp.path())
            .env_remove("LYREL_PI_BRIDGE_OWNER")
            .output()
            .unwrap();
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        let mut state = crate::core::cli_agent::AgentSessionState::default();
        for (index, line) in String::from_utf8(output.stdout)
            .unwrap()
            .lines()
            .enumerate()
        {
            let payload: serde_json::Value = serde_json::from_str(line).unwrap();
            let body = crate::core::agent_hooks::build_hook_body(
                "pi",
                payload["event"].as_str().unwrap(),
                line,
            );
            let event = crate::core::cli_agent::parse_agent_event_body(body.as_bytes()).unwrap();
            state.apply_event(&event);
            if index == 4 {
                assert_eq!(state.pending_requests.len(), 1);
                assert_eq!(state.status, crate::core::cli_agent::AgentStatus::Waiting);
            }
            if index == 8 {
                assert!(state.pending_requests.is_empty());
                assert_eq!(state.status, crate::core::cli_agent::AgentStatus::Done);
            }
        }
        assert_eq!(
            state.readout.result.unwrap().outcome,
            crate::core::cli_agent::AgentOutcome::Interrupted
        );
    }
}
